#!/usr/bin/env bash
# Upload code / data / TerraMind weights from the lab machine to Nano5 over sftp
# (data-transfer node, port 2222). One ControlMaster connection is opened first,
# so the 2FA prompt appears once.
#
# Usage (run on the lab machine, from any directory):
#   bash scripts/nchc/push.sh code            # tracked + untracked-not-ignored files of this checkout
#   bash scripts/nchc/push.sh data            # WorldFloods v2 S2/gt + dataset_metadata.csv (~93 GB, resumable)
#   bash scripts/nchc/push.sh hf              # TerraMind-1.0-base HF cache (offline use on compute nodes)
#   bash scripts/nchc/push.sh dir LOCAL REMOTE_REL   # any other dir, symlinks dereferenced, to $NCHC_WORK/REMOTE_REL
#   bash scripts/nchc/push.sh all             # code + hf + data
#
# Data uploads use `put -a` (resume), so an interrupted run can simply be repeated.
# windows_*.json / train_test_split_from_csv.json are not uploaded: they hold absolute
# /home/NAS paths and are regenerated by the training script on Nano5.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
source "$SCRIPT_DIR/env.sh"

if [[ "$NCHC_USER" == "$USER" && ! -f "$SCRIPT_DIR/nchc.env" ]]; then
  echo "scripts/nchc/nchc.env not found; copy nchc.env.example and set NCHC_USER" >&2
  exit 1
fi

read -r -a SSH_OPTS <<<"$(nchc_ssh_opts "$NCHC_XFER_PORT")"
SFTP_OPTS=("-P" "$NCHC_XFER_PORT" "${SSH_OPTS[@]:2}")
REMOTE="$NCHC_USER@$NCHC_HOST"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

open_master() {
  # `sftp -b` forces BatchMode (no password/2FA prompts), so authenticate once
  # with a background master connection that the batch runs then reuse.
  ssh "${SSH_OPTS[@]}" -O check "$REMOTE" 2>/dev/null && return 0
  echo "Opening connection to $REMOTE:$NCHC_XFER_PORT (2FA prompt follows)"
  ssh "${SSH_OPTS[@]}" -fN "$REMOTE"
}

# Lines starting with '-' may fail without aborting the batch (e.g. mkdir of an existing dir).
run_batch() {
  local batch="$STAGE/batch.$RANDOM"
  cat >"$batch"
  sftp "${SFTP_OPTS[@]}" -b "$batch" "$REMOTE"
}

mkdir_lines() {
  # Emit "-mkdir" for every prefix of an absolute remote path.
  local path="$1" acc=""
  IFS='/' read -r -a parts <<<"${path#/}"
  for p in "${parts[@]}"; do
    acc="$acc/$p"
    echo "-mkdir $acc"
  done
}

push_code() {
  local dst="$STAGE/flood-uncertainty"
  mkdir -p "$dst"
  (cd "$PROJECT_ROOT" && git ls-files -co --exclude-standard -z | tar --null -T - -cf -) | tar -xf - -C "$dst"
  echo "Uploading code ($(du -sh "$dst" | cut -f1)) -> $NCHC_REPO"
  {
    mkdir_lines "$(dirname "$NCHC_REPO")"
    echo "cd $(dirname "$NCHC_REPO")"
    echo "lcd $STAGE"
    echo "put -r flood-uncertainty"
  } | run_batch
}

push_data() {
  local src="$LAB_DATA/worldfloods_v2" dst="$NCHC_DATA/worldfloods_v2"
  {
    mkdir_lines "$dst"
    echo "put $src/dataset_metadata.csv $dst/dataset_metadata.csv"
    for split in train val test; do
      local real
      real="$(realpath "$src/$split")"
      echo "-mkdir $dst/$split"
      echo "cd $dst/$split"
      echo "lcd $real"
      for mod in S2 gt; do
        echo "-put -r -a $mod"
      done
    done
  } | run_batch
}

push_hf() {
  local repo="models--ibm-esa-geospatial--TerraMind-1.0-base"
  local src="$LAB_HF_HOME/hub/$repo"
  # Snapshots are symlinks into blobs/; dereference so only the used files travel.
  mkdir -p "$STAGE/$repo"
  cp -rL "$src/refs" "$src/snapshots" "$STAGE/$repo/"
  {
    mkdir_lines "$NCHC_HF_HOME/hub"
    echo "cd $NCHC_HF_HOME/hub"
    echo "lcd $STAGE"
    echo "put -r $repo"
  } | run_batch
}

push_dir() {
  local src="$1" rel="$2"
  local name
  name="$(basename "$rel")"
  mkdir -p "$STAGE/$name"
  cp -rL "$src/." "$STAGE/$name/"
  {
    mkdir_lines "$NCHC_WORK/$(dirname "$rel")"
    echo "cd $NCHC_WORK/$(dirname "$rel")"
    echo "lcd $STAGE"
    echo "put -r -a $name"
  } | run_batch
}

target="${1:-}"
case "$target" in
  code) open_master; push_code ;;
  data) open_master; push_data ;;
  hf)   open_master; push_hf ;;
  dir)
    [[ $# -eq 3 ]] || { echo "usage: push.sh dir LOCAL REMOTE_REL" >&2; exit 2; }
    open_master; push_dir "$2" "$3" ;;
  all)  open_master; push_code; push_hf; push_data ;;
  *) sed -n '2,16p' "$0"; exit 2 ;;
esac
echo "push $target done"
